package com.myproject.radiojourney.presentation.common

/**
 * Короткое имя станции для нижнего плеера.
 *
 * Зачем: в каталоге radio-browser почти все названия короткие (у половины станций - до 17 символов, у 9 из 10 - до 32),
 * но около 1,5% длиннее 80 символов, а самое длинное - 399. Такие названия почти всегда не название, а список
 * ключевых слов для поиска: ">> *TOP 100 CHARTS* << || Pop, Rock, Dance, House, ..." (проверено на 20 000 самых
 * популярных станций каталога). В одной строке плеера бегущая строка ехала бы с ним больше двух минут.
 *
 * Правило: короткие названия (до SHORT_ENOUGH символов) не трогаем. У длинных ищем явный разделитель (||, |, @, • и т.п.)
 * и оставляем часть до него, убрав украшения по краям (*, >>, #). В списках станций по-прежнему показывается
 * полное название: там список жанров может помочь выбрать станцию
 */

// Название такой длины помещается или почти помещается в строку плеера - его не сокращаем
private const val SHORT_ENOUGH = 40

// Разделители, после которых у длинных названий обычно начинается слоган или список жанров. Порядок важен:
// сначала самые "сильные". Обычный " - " последний: он часто бывает внутри настоящего названия ("Radio X - Rock")
private val SEPARATORS = listOf("||", " | ", " @ ", " • ", " :: ", " — ", " – ", " -> ", " - ")

// Украшения по краям: звёздочки, стрелки, решётки, тире, подчёркивания, сердечки "<3"
private val DECORATION_AT_EDGES = Regex("^(?:[\\s*#>\\-_~=.]|<3)+|(?:[\\s*#<\\-_~=.]|<3)+$")

fun shortStationName(name: String): String {
    val full = name.trim()
    if (full.length <= SHORT_ENOUGH) return full

    for (separator in SEPARATORS) {
        if (!full.contains(separator)) continue
        // Первая часть, в которой есть хотя бы три буквы или цифры: у ">> *TOP 100 CHARTS* << || ..." первая часть
        // и так годится, а у "|| Radio X || ..." пустой первой части нет смысла - берём следующую
        val part = full.split(separator)
            .map { it.replace(DECORATION_AT_EDGES, "").trim() }
            .firstOrNull { part -> part.count { it.isLetterOrDigit() } >= 3 }
        // Отрезанная часть всё ещё длинная - укорачиваем её дальше тем же способом (по следующему разделителю)
        if (part != null) return if (part.length > SHORT_ENOUGH && part != full) shortStationName(
            part
        ) else part
    }
    return full.replace(DECORATION_AT_EDGES, "").trim()
}