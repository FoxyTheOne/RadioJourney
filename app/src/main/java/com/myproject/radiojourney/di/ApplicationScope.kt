package com.myproject.radiojourney.di

import javax.inject.Qualifier

/**
 * Корутинный scope приложения: живёт, пока живёт процесс.
 *
 * Нужен для работы, которая не должна отменяться вместе с экраном. Пример: пользователь что-то нажал,
 * экран сразу закрылся, а запись в базу или в настройки не успела дойти до диска - в viewModelScope такая
 * корутина отменилась бы вместе с ViewModel (рекомендация developer.android.com).
 *
 * Сейчас в приложении никто его не просит: единственным местом был выход из аккаунта, а его больше нет.
 * Оставлен как готовый образец на будущее (и потому что он ничего не стоит, пока его не внедряют)
 */
@Qualifier
@Retention(AnnotationRetention.BINARY)
annotation class ApplicationScope