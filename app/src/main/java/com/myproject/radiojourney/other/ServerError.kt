package com.myproject.radiojourney.other

/**
 * Почему не удалось получить данные с сервера radio-browser.
 *
 * Раньше при любой неудаче пользователь видел одно и то же окно "В ответ на запрос получен пустой список",
 * хотя причины бывают разные, и сделать с ними можно разное. Причину определяет NetworkRadioDataSource
 * по тому, на каком этапе запрос сломался, и передаёт её в Resource.error (message = name)
 */
enum class ServerError {
    // Телефон не подключён к сети (режим полёта, выключены Wi-Fi и мобильные данные)
    NO_NETWORK,

    // Сервер не ответил: не удалось подключиться, ответ с ошибкой (например, 503) или пустой список
    SERVER_NOT_RESPONDING,

    // Сервер начал отвечать, но ответ оборвался на середине. Так выглядит ограничение доступа к зарубежным
    // хостингам на стороне провайдера: с сервера проходят только первые ~16 КБ, дальше соединение обрывается
    // (так с лета 2025 года ограничивают Hetzner, где стоит сервер radio-browser, некоторые российские провайдеры)
    CONNECTION_CUT;

    companion object {
        // Обратно из Resource.message. Незнакомое значение (или null) - "сервер не ответил"
        fun fromMessage(message: String?): ServerError =
            entries.firstOrNull { it.name == message } ?: SERVER_NOT_RESPONDING
    }
}